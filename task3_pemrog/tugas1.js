let nilai = 85;

if (nilai >= 80 && nilai <= 100) {
    console.log("Nilai A");
} else if (nilai >= 70) {
    console.log("Nilai B");
} else if (nilai >= 60) {
    console.log("Nilai C");
} else if (nilai >= 50) {
    console.log("Nilai D");
} else if (nilai >= 0) {
    console.log("Nilai E");
} else {
    console.log("Nilai tidak valid");
}